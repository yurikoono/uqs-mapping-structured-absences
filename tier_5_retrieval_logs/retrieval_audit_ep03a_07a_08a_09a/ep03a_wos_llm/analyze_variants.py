#!/usr/bin/env python3
"""Parse all WoS variant exports, extract key metadata, and check DOI/author overlap
against the LLM-identified EP-03a filling candidates."""
import re
from pathlib import Path

HERE = Path(__file__).parent

# Target LLM candidates (from llm_candidates_ep03a.md)
LLM_CANDIDATES = [
    {"label": "Parshall 1974 JACS", "doi": "10.1021/ja00815a017",
     "authors": ["parshall"], "year": 1974, "journal_frag": "AMERICAN CHEMICAL"},
    {"label": "Morrell-Kochi 1975 JACS", "doi": "10.1021/ja00858a011",
     "authors": ["morrell", "kochi"], "year": 1975, "journal_frag": "AMERICAN CHEMICAL"},
    {"label": "Yamamoto 1978 BCSJ", "doi": "10.1246/bcsj.51.2091",
     "authors": ["yamamoto"], "year": 1978, "journal_frag": "CHEMICAL SOCIETY OF JAPAN"},
    {"label": "Anderson-Jones-Vicic 2004 JACS", "doi": "10.1021/ja0488380",
     "authors": ["anderson", "vicic"], "year": 2004, "journal_frag": "AMERICAN CHEMICAL"},
    {"label": "Jones-Martin-McMurdo-Vicic 2006 JACS", "doi": "10.1021/ja063334i",
     "authors": ["mcmurdo", "vicic"], "year": 2006, "journal_frag": "AMERICAN CHEMICAL"},
    {"label": "Dawson 2020 Chem.Eur.J.", "doi": "10.1002/chem.202000215",
     "authors": ["dawson"], "year": 2020, "journal_frag": "CHEMISTRY-A EUROPEAN"},
]

VARIANTS = {
    "v1": "wos_raw_49hits.txt",
    "A": "wos_variant_a.txt",
    "B": "wos_variant_b.txt",
    "C": "wos_variant_c.txt",
    "D": "wos_variant_d.txt",
}


def parse_wos(path: Path) -> list[dict]:
    records = []
    current = {}
    current_tag = None
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        if line == "ER":
            if current:
                records.append(current)
            current = {}
            current_tag = None
            continue
        if line.startswith("EF") or line.startswith("FN ") or line.startswith("VR "):
            continue
        m = re.match(r"^([A-Z0-9]{2})\s(.*)$", line)
        if m:
            current_tag = m.group(1)
            current[current_tag] = m.group(2)
        elif line.startswith("   ") and current_tag:
            current[current_tag] = current.get(current_tag, "") + " " + line.strip()
    return records


def match_candidate(record: dict, cand: dict) -> str | None:
    """Return a short reason string if record matches candidate, else None."""
    di = record.get("DI", "").lower()
    if cand["doi"].lower() == di:
        return f"DOI match ({di})"
    au = record.get("AU", "").lower()
    ti = record.get("TI", "").lower()
    py = record.get("PY", "")
    author_hits = [a for a in cand["authors"] if a in au]
    year_match = str(cand["year"]) == py.strip()
    if len(author_hits) >= 1 and year_match:
        return f"author+year match ({','.join(author_hits)} / {py})"
    return None


def main():
    # Parse all variants
    variant_records: dict[str, list[dict]] = {}
    for key, fname in VARIANTS.items():
        p = HERE / fname
        variant_records[key] = parse_wos(p)

    # Check LLM-candidate overlap per variant
    overlap_matrix = []
    for key, recs in variant_records.items():
        row = {"variant": key, "N": len(recs)}
        for cand in LLM_CANDIDATES:
            hit_reason = None
            for i, r in enumerate(recs, 1):
                reason = match_candidate(r, cand)
                if reason:
                    hit_reason = f"#{i}: {reason}"
                    break
            row[cand["label"]] = hit_reason or "-"
        overlap_matrix.append(row)

    # DOI sets for cross-variant overlap
    def doi_set(recs):
        return {r.get("DI", "").lower() for r in recs if r.get("DI")}

    doi_sets = {k: doi_set(recs) for k, recs in variant_records.items()}

    # Generate report
    lines = [
        "# Cross-Variant Analysis: EP-03a WoS Queries vs LLM Candidates",
        "",
        "Generated by `analyze_variants.py`. See `wos_query_alternatives.md` for query design and `llm_candidates_ep03a.md` for LLM candidate list.",
        "",
        "## Record counts",
        "",
        "| Variant | N (records returned) |",
        "|---|---|",
    ]
    for row in overlap_matrix:
        lines.append(f"| {row['variant']} | {row['N']} |")

    lines += [
        "",
        "## LLM-candidate recovery per variant",
        "",
        "Checked by DOI exact match or (first-author surname + year) fuzzy match.",
        "",
        "| LLM candidate | v1 | A | B | C | D |",
        "|---|---|---|---|---|---|",
    ]
    for cand in LLM_CANDIDATES:
        cols = []
        for key in VARIANTS:
            row = next(r for r in overlap_matrix if r["variant"] == key)
            val = row[cand["label"]]
            cols.append("**✓**" if val != "-" else "-")
        lines.append(f"| {cand['label']} | " + " | ".join(cols) + " |")

    # Detailed hit reasons (only where found)
    lines += [
        "",
        "### Hit details",
        "",
    ]
    for cand in LLM_CANDIDATES:
        hits = []
        for key in VARIANTS:
            row = next(r for r in overlap_matrix if r["variant"] == key)
            v = row[cand["label"]]
            if v != "-":
                hits.append(f"- **{key}**: {v}")
        if hits:
            lines.append(f"**{cand['label']}**")
            lines.extend(hits)
            lines.append("")
        else:
            lines.append(f"**{cand['label']}**: not retrieved by any variant")
            lines.append("")

    # Cross-variant overlap (DOI set-based)
    lines += [
        "## Cross-variant record overlap (DOI-based)",
        "",
        "| | v1 | A | B | C | D |",
        "|---|---|---|---|---|---|",
    ]
    for k1 in VARIANTS:
        row = [f"| **{k1}**"]
        for k2 in VARIANTS:
            s1, s2 = doi_sets[k1], doi_sets[k2]
            if k1 == k2:
                row.append(f"{len(s1)}")
            else:
                row.append(f"{len(s1 & s2)}")
        lines.append(" | ".join(row) + " |")

    # Union across variants
    all_dois = set().union(*doi_sets.values())
    lines += [
        "",
        f"**Union of all variants**: {len(all_dois)} unique DOIs",
        "",
        "## Note on export caps",
        "",
        "WoS default export is capped at 500; single-session export may be 50 or 1000 depending on UI. If Variants A or C show exactly 50 records, the actual result set may be larger; re-export with increased batch size to confirm.",
    ]

    out = HERE / "variant_analysis_report.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")

    # Also print quick summary to stdout
    print("\n=== Summary ===")
    for row in overlap_matrix:
        found = sum(1 for c in LLM_CANDIDATES if row[c["label"]] != "-")
        print(f"  {row['variant']}: N={row['N']}, LLM candidates found={found}/{len(LLM_CANDIDATES)}")


if __name__ == "__main__":
    main()
